/** The app's logo drawn as an outline in the current text colour: decorative, the app's name is in the tooltip. */
export function LauncherOutline({ id, className }: { id: LauncherId; className?: string }) {
  const clip = useId()

  if (id === 'vscode') {
    return (
      <svg
        viewBox="-12 -12 280 280"
        fill="none"
        stroke="currentColor"
        strokeWidth={18}
        strokeLinejoin="round"
        aria-hidden="true"
        className={className}
      >
        <path fillRule="evenodd" d={VSCODE} />
      </svg>
    )
  }

  // The ram is drawn in the logo's own 1024 space and cut by the rounded tile it sits in
  return (
    <svg
      viewBox="130 130 840 840"
      fill="none"
      stroke="currentColor"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      <clipPath id={clip}>
        <rect x="64" y="64" width="896" height="896" rx="192" />
      </clipPath>
      <g clipPath={`url(#${clip})`}>
        <path d={HERDR_RAM} transform="translate(-80 967) scale(.22 -.22)" strokeWidth={52 / 0.22} />
      </g>
    </svg>
  )
}
